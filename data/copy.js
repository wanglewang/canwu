function formatRank(rank) {
    return rank > 0 ? '榜上第 ' + rank + ' 名' : '暂未上榜';
}

function formatRankGap(gap, rankLimit) {
    return gap > 0 ? ' · 距第 ' + rankLimit + ' 名还差 ' + gap + ' 战力' : '';
}

