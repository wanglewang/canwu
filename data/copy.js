function termOf(key) {
    for (let i = 0; i < TERMS.length; i += 1) if (TERMS[i].key === key) return TERMS[i];
    return null;
}

// 境界超限：只影响「一局烧多少灵力」，不影响能不能练、也不影响进度。
// 必须写明「照样能练」：只写「已超可修上限」，玩家会读成「这门作废了」——
// 金丹期练黄阶正是这个误读的高发处（黄阶上限只到筑基）。
function decayText(kind, realmName) {
    // 两件事必须分开说：超上限是「加价」（还能练），未到门槛是「修不动」（连开局都不给）。
    // 把未到门槛也写成「耗气 ×1.5」，等于告诉玩家这门还能练——他点进去只会被拒。
    if (kind !== 'above') {
        return '人物境界未到「' + realmName + '」门槛：这一门现在修不动，先把境界提上去。';
    }
    return '人物境界已超本门可修上限「' + realmName + '」，照样能练，本局耗气 ×1.5；'
        + '进度照推，属性加成照拿，评级门槛不变。';
}

// 参悟准备页的耗气口径：只奖不罚。开局前就说清这一局会不会吃到换门优惠。
function practiceNote(cross, crossQi) {
    const save = '触类旁通 · 耗气 ×' + Number(crossQi).toFixed(2);
    return cross
        ? '本局换了功法 · ' + save
        : '同一门连练没有额外代价 · 换一门另有' + save;
}

// 藏经阁的价格：只收灵石。灵力是练功的燃料，不参与交易。
function formatCost(stone) {
    return '灵石 ' + stone;
}

// 一份收获的写法：先气后石，为 0 的那一项不写。
// 参悟不产资源之后，这里只剩「每日份例」在用——份例给的是灵力，灵石一分不给。
function formatGain(qi, stone) {
    const parts = [];
    if (qi > 0) parts.push('灵力 +' + qi);
    if (stone > 0) parts.push('灵石 +' + stone);
    return parts.length ? parts.join(' / ') : '没有所得';
}

