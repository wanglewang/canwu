// 名词速查直接由 data/copy.js 的术语表生成：页面上「?」弹层与这里读的是同一份解释。
const DEMO_TERM = 'mijing';

function glossarySection(no) {
    const order = [];
    const byGroup = {};
    for (const t of copy.TERMS) {
        if (!byGroup[t.group]) { byGroup[t.group] = []; order.push(t.group); }
        byGroup[t.group].push(t.name + '：' + t.desc);
    }
    const lines = [copy.UI.hints.glossary];
    for (const g of order) {
        lines.push('【' + g + '】');
        for (const l of byGroup[g]) lines.push(l);
    }
    return {
        title: no + ' · ' + copy.UI.sections.glossary,
        sub: '黑话第一次出现时，页面上也有「?」可以点',
        lines: lines,
        // 示范一个真的「?」：光说「可以点」，玩家不会知道它长什么样。
        demo: DEMO_TERM,
    };
}
SECTIONS.push(glossarySection('十二'));

Page({
    data: {
        sections: SECTIONS.map(function (s, i) {
            return Object.assign({}, s, {
                id: 'sec-' + i,
                short: s.title.split(' · ')[1] || s.title,
                open: i === 0,
            });
        }),
        allOpen: false,
        copy: copy.UI,
    },

    // 十几节长文不该一屏铺到底：目录直达 + 单节展开 + 一键全展开 / 全收起。
    // 只有 sections[i].open 这一套状态，不再另设 showAll —— 两套状态并存时，
    // 全局展开着点某一节标题会「点了没反应」，是改版前的真 bug。
    onToggleSection: function (event) {
        const i = Number(event.currentTarget.dataset.index);
        const patch = {};
        patch['sections[' + i + '].open'] = !this.data.sections[i].open;
        patch.allOpen = false;
        this.setData(patch);
    },

    onJump: function (event) {
        const target = Number(event.currentTarget.dataset.index);
        const patch = { allOpen: false };
        for (let i = 0; i < this.data.sections.length; i += 1) {
            patch['sections[' + i + '].open'] = i === target;
        }
        this.setData(patch, function () {
            wx.pageScrollTo({ selector: '#sec-' + target, duration: 240, fail: function () {} });
        });
    },

    onToggleAll: function () {
        const next = !this.data.allOpen;
        const patch = { allOpen: next };
        for (let i = 0; i < this.data.sections.length; i += 1) {
            patch['sections[' + i + '].open'] = next;
        }
        this.setData(patch);
    },

    onGoAction: function (event) {
        const i = Number(event.currentTarget.dataset.index);
        const act = this.data.sections[i].action;
        if (!act) return;
        // 藏品与功法都在功法页：先记下去向，切过去时由功法页自己认这个标记。
        if (act.kind === 'tabSkills') {
            getApp().globalData.skillsTab = act.tab || 'learned';
            wx.switchTab({ url: '/pages/skills/skills' });
            return;
        }
        wx.navigateTo({ url: act.url });
    },

    onGoHelp: function () { wx.navigateTo({ url: nav.helpUrl('guide') }); },

    onShareAppMessage: function () { return share.appMessage(store.get()); },
    onShareTimeline: function () { return share.timeline(store.get()); },
});
